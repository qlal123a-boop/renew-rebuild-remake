export function subjectsForGrade(gradeId: number): string[] {
  const explicit = SUBJECTS_BY_GRADE[gradeId];
  if (explicit && explicit.length) return explicit;
  const g = GRADES.find((x) => x.id === gradeId);
  return g ? SUBJECTS_BY_STAGE[g.stage] : [];
}

