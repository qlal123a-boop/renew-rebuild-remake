export function slugifySubject(subject: string): string {
  // stable ASCII-ish slug from index in stage list
  return encodeURIComponent(subject);
}

export function generateDefaultLessons(): Lesson[] {
  const lessons: Lesson[] = [];
  for (const g of GRADES) {
    const subjects = SUBJECTS_BY_STAGE[g.stage];
    for (const subject of subjects) {
      for (const sem of [1, 2] as const) {
        const titles = pickTemplate(g.id, subject, sem);
        titles.forEach((title, idx) => {
          // Default video: a YouTube search query for the lesson + grade + subject
          const query = encodeURIComponent(`${title} ${subject} ${g.name} روافد`);
          lessons.push({
            id: `g${g.id}-${slugifySubject(subject)}-s${sem}-${idx}`,
            gradeId: g.id,
            subject,
            semester: sem,
            title,
            description: `شرح درس "${title}" في مادة ${subject} ${g.name} — الفصل ${sem === 1 ? "الأول" : "الثاني"}. اضغط زر الفيديو لمشاهدة الشرح المرئي.`,
            videoUrl: `https://www.youtube.com/results?search_query=${query}`,
          });
        });
      }
    }
  }
  return lessons;
}
